// Grocery store retailers we recognise as "stores" (vs. brand companies).
// The Shop tab's store filter chip row uses this list.
const GROCERY_STORES = new Set<string>([
  "Trader Joe's",
  "ShopRite",
  "A&P",
  "Kings",
  "Whole Foods",
  "Wegmans",
  "Aldi",
  "Costco",
  "Target",
  "Quick Check",
  "7-Eleven",
]);

// Unique grocery-store brands present in the catalog, sorted alphabetically.
// Powers the "Stores" filter chip row on the Shop tab.
export const STORES: string[] = Array.from(
  new Set(PRODUCTS.map((p) => p.brand).filter((b) => GROCERY_STORES.has(b))),
).sort();

export function findProduct(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function findByBarcode(code: string): Product | undefined {
  return PRODUCTS.find((p) => p.barcode === code);
}

export function getGreenAlternative(id: string): Product | undefined {
  const p = findProduct(id);
  if (!p?.greenAlternativeId) return undefined;
  return findProduct(p.greenAlternativeId);
}
